export function classifyQuery(text) {
  const t = text.toLowerCase();
  let best = null;
  let bestScore = 0;
  chatIntents.forEach((intent) => {
    let score = 0;
    intent.keywords.forEach((kw) => {
      if (t.includes(kw)) score += kw.length;
    });
    if (score > bestScore) {
      bestScore = score;
      best = intent;
    }
  });
  return best;
}

