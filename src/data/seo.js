/**
 * src/data/seo.js — everything a crawler/scraper reads, derived from the
 * positioning layer rather than retyped (T-014, closes gate FAIL #10).
 *
 * The two failures T-007 found were "the site ships six statements" (#7) and
 * "there is nothing for a crawler" (#10). Re-typing the title into the OG tags
 * would have re-created #7 in the `<head>`, so the OG/JSON-LD block is built
 * from src/data/positioning.js and injected into index.html at build time by
 * the `positioningHtml` plugin in vite.config.js.
 *
 * Facts asserted here are copied from src/data/profile.js (name, locality,
 * profile URLs) — nothing on this page is invented.
 */
import { TITLE_TAG, TAGLINE, META_DESCRIPTION } from './positioning.js';
import { profile } from './profile.js';
import { SITE_URL } from './site.js';

/** Trailing slash: the canonical form of the single-page site. */
export const CANONICAL_URL = `${SITE_URL}/`;

/** 1200x630 card generated by `npm run build:og` (scripts/build-og-image.mjs). */
export const OG_IMAGE_URL = `${SITE_URL}/og-image.png`;
export const OG_IMAGE_WIDTH = 1200;
export const OG_IMAGE_HEIGHT = 630;
export const OG_IMAGE_ALT = `${TAGLINE} — 200M-record database performance, measured.`;

/** og:type — a person's profile page, not a generic website. */
export const OG_TYPE = 'profile';

/**
 * JSON-LD `Person`. Serialised into index.html as-is; keeps `sameAs` pointed at
 * the profiles that already exist (profile.js) so nothing here is a new claim.
 */
export const PERSON_JSON_LD = {
  '@context': 'https://schema.org',
  '@type': 'Person',
  name: profile.name,
  jobTitle: TAGLINE,
  description: META_DESCRIPTION,
  url: CANONICAL_URL,
  image: OG_IMAGE_URL,
  knowsLanguage: 'en',
  address: {
    '@type': 'PostalAddress',
    addressLocality: 'Indore',
    addressRegion: 'MP',
    addressCountry: 'IN',
  },
  sameAs: [profile.linkedin, profile.github].filter(Boolean),
};

/** Pretty-printed so a human reading view-source can audit it. */
export const jsonLd = () => JSON.stringify(PERSON_JSON_LD, null, 2);

/** Guard: the injected values must not silently become an empty string. */
export const TITLE_FOR_CRAWLER = TITLE_TAG;
